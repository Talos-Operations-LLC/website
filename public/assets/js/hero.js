import { multiply, axisAngle, fromCamera, dragRotation, slerp, matrix } from './globe-rotation.js';

/* ============================================================================
   Fee Simple hero field.
   A dotted globe, every continent in the blue glow, spins, turns to North
   America and zooms in until the continental US fills the box. The dense US
   map holds while white filaments crawl its web, then the view pulls back to
   the globe and the loop repeats (~23s). Pointer interaction is described below.

   Geometry is generated by tools/gen_hero_geo.py from Natural Earth data:
     GEO.world  land dots on an even grid, the US cut out     (lon, lat x10)
     GEO.us     the continental US on a fine jittered grid    (lon, lat x100)
   A thin subset of the US dots stands in for it on the globe; the rest fade
   in as the zoom closes, so detail arrives with the camera.

   Palette: one theme, the Fee Simple blues — cyan-blue -> electric blue only,
   warped into irregular clusters by coarse noise; additive blending blooms
   dense regions toward white. Depth (random z) drives size, brightness and
   drift so big bright points hang over tiny dim ones.

   Drawing: WebGL, every dot in ONE draw call per frame (point sprites with
   the glow computed in the shader, additive blending). Lines are thin quads
   with a feathered edge. If the browser has no WebGL, the 2D-canvas path
   below paints the same frame from the same arrays, one sprite at a time.

   The pointer: moving the mouse across the field pushes nearby dots aside
   and they spring back, so a sweep leaves a wake. Pressing and dragging
   rotates the globe freely like a trackball, with a little coast on release.
   Dragging pauses the tour, which resumes after ten seconds without interaction.
   Touch supports horizontal dragging while leaving vertical page scrolling free.

   Performance choices (each tunable):
   - every dot is a precomputed unit vector, rotated by one shared matrix
   - the far side of the globe and anything outside the box are skipped
   - roughly 7.6k dots on desktop (fewer drawn after culling), half that on phones
   - devicePixelRatio up to 2 on WebGL (crisp on Retina), 1.5 on the 2D fallback
   - the machine sets the pace (see "the governor"): a machine that cannot keep
     the loop smooth steps down to lite (every other dot, no Retina), then to
     still (one frame of the globe holds; dragging and keys still redraw it).
     Software-only WebGL is refused and a lost context gives way to the 2D path,
     which the governor paces the same way. The loop rests while the field is
     off screen, so the rest of the page has the whole CPU.
   Loads local geometry once; no animation libraries.
   ========================================================================== */
async function startHero() {
  const response = await fetch('/assets/data/hero-geometry.json');
  if (!response.ok) throw new Error(`Hero geometry failed to load (${response.status})`);
  const GEO = await response.json();

  let canvas = document.getElementById('field');
  // The field fills its box, not the window, so content can sit around it.
  const hero = canvas.parentElement;
  const reduced = matchMedia('(prefers-reduced-motion: reduce)').matches;
  // WebGL first; the 2D context only if the browser has no WebGL (see the bootstrap).
  // Transparent, like the 2D canvas was: the page's own background shows through,
  // so there is no opaque layer for the browser to colour-shift against the page.
  // failIfMajorPerformanceCaveat: a browser that could only draw WebGL in software
  // says no instead, and the 2D path takes over at a pace that machine can hold.
  let gl = canvas.getContext('webgl', { alpha: true, premultipliedAlpha: true, antialias: false,
                                        depth: false, stencil: false, powerPreference: 'high-performance',
                                        failIfMajorPerformanceCaveat: true });
  // A driver that caps point sprites near one pixel would leave the dots invisible: 2D there too.
  if (gl) {
    const range = gl.getParameter(gl.ALIASED_POINT_SIZE_RANGE);
    if (!range || range[1] < 12) gl = null;
  }
  let ctx = null;                            // the 2D context, once useCanvas2D() has made its canvas

  // ---- color: the blue band --------------------------------------------------
  // Hue lives in [196, 234]: cyan-blue -> pure blue, nothing past blue (no
  // violet). The angular ramp gives loose structure; noise breaks it into blotches.
  const BAND_LO = 196, BAND_HI = 234;
  const HUE_RAMP = [203, 218, 231, 210, 199, 224, 203];   // sweep within the band
  function hueAt(a01) {
    const f = a01 * (HUE_RAMP.length - 1), i = Math.floor(f), u = f - i;
    return HUE_RAMP[i] + (HUE_RAMP[i + 1] - HUE_RAMP[i]) * u;
  }
  const CELL = 110, GRID = new Map();
  function cellVal(ix, iy) {
    const k = ix + ',' + iy;
    let v = GRID.get(k);
    if (v === undefined) { v = Math.random(); GRID.set(k, v); }
    return v;
  }
  function noise2(x, y) {
    const gx = x / CELL, gy = y / CELL, ix = Math.floor(gx), iy = Math.floor(gy);
    const fx = gx - ix, fy = gy - iy, sx = fx * fx * (3 - 2 * fx), sy = fy * fy * (3 - 2 * fy);
    const a = cellVal(ix, iy), b = cellVal(ix + 1, iy), c = cellVal(ix, iy + 1), d = cellVal(ix + 1, iy + 1);
    return a + (b - a) * sx + (c - a) * sy + (a - b - c + d) * sx * sy;
  }
  function hslToRgb(h, s, l) {
    h = ((h % 360) + 360) % 360;
    const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs((h / 60) % 2 - 1)), m = l - c / 2;
    let r = 0, g = 0, b = 0;
    if (h < 60) { r = c; g = x; } else if (h < 120) { r = x; g = c; }
    else if (h < 180) { g = c; b = x; } else if (h < 240) { g = x; b = c; }
    else if (h < 300) { r = x; b = c; } else { r = c; b = x; }
    return [(r + m) * 255 | 0, (g + m) * 255 | 0, (b + m) * 255 | 0];
  }

  // ---- glow sprites ----------------------------------------------------------
  // 24 sprites spanning the blue band; particles drawImage these additively.
  const SPRITES = [], BUCKETS = 24, SPR = 28;
  function makeSprites() {
    SPRITES.length = 0;
    for (let b = 0; b < BUCKETS; b++) {
      const off = document.createElement('canvas');
      off.width = off.height = SPR;
      const c = off.getContext('2d');
      const hue = BAND_LO + (b / (BUCKETS - 1)) * (BAND_HI - BAND_LO);
      const [r, g, bl] = hslToRgb(hue, 0.85, 0.62);
      const grad = c.createRadialGradient(SPR/2, SPR/2, 0, SPR/2, SPR/2, SPR/2);
      grad.addColorStop(0,    'rgba(255,255,255,0.9)');            // hot core
      grad.addColorStop(0.18, 'rgba(' + r + ',' + g + ',' + bl + ',0.85)');
      grad.addColorStop(0.5,  'rgba(' + r + ',' + g + ',' + bl + ',0.1)');
      grad.addColorStop(1,    'rgba(' + r + ',' + g + ',' + bl + ',0)');
      c.fillStyle = grad;
      c.fillRect(0, 0, SPR, SPR);
      SPRITES.push(off);
    }
  }
  function bucketFor(hue) {
    const h = Math.max(BAND_LO, Math.min(BAND_HI, hue));
    return Math.round((h - BAND_LO) / (BAND_HI - BAND_LO) * (BUCKETS - 1));
  }
  // white endpoint sprite for the "connecting the country" pulses
  let WHITE;
  function makeWhite() {
    WHITE = document.createElement('canvas');
    WHITE.width = WHITE.height = SPR;
    const c = WHITE.getContext('2d');
    const grad = c.createRadialGradient(SPR/2, SPR/2, 0, SPR/2, SPR/2, SPR/2);
    grad.addColorStop(0,    'rgba(255,255,255,0.95)');
    grad.addColorStop(0.2,  'rgba(255,255,255,0.9)');
    grad.addColorStop(0.55, 'rgba(255,255,255,0.25)');
    grad.addColorStop(1,    'rgba(255,255,255,0)');
    c.fillStyle = grad;
    c.fillRect(0, 0, SPR, SPR);
  }

  // ---- the globe -------------------------------------------------------------
  // Orthographic view of a unit sphere. Each dot keeps its unit vector; a frame
  // applies the camera quaternion as a rotation matrix, including free roll:
  //   x  = east-west on screen, y = north-south, zc = toward the viewer (hidden if <= 0)
  const D2R = Math.PI / 180;
  const US_LON = -98.2, US_LAT = 38.8;      // where the zoom lands
  const GLOBE_LAT = 16;                     // the globe's tilt toward the viewer
  const SPIN = 9;                           // degrees per second the globe turns

  let W = 0, H = 0, dpr = 1, scale = 1;     // the canvas, which overflows its box (see layout)
  let BW = 0, BH = 0;                       // the box the map is laid out in
  const PAD_X = 0.3, PAD_Y = 0.5;           // overflow past the box, as fractions of its size, so the zoom is never clipped
  const EDGE = 70;                          // px: dots fade out this close to the canvas edge instead of being cut off
  let R_GLOBE = 1, R_LAND = 1;              // sphere radius in px: on the globe, and landed
  const P = [];            // every dot, world and US
  const US = [];           // indices into P of the US dots (links, strings, framing)
  const LINKS = [];        // [i, j] pairs; drawn as one batched path
  const ADJ = [];          // walk graph: per-particle neighbor indices (US only)
  // The landed US map lives on a plane (like a 960-wide sheet) so link distances,
  // noise cells and the hue sweep keep their units. DATA is that sheet's size.
  const DATA = { w: 960, h: 600 };
  let kplane = 1, bx0 = 0, by1 = 0;         // unit sphere -> sheet
  const UC = [0, 0];                        // the US's centre on the unit sphere, landed

  function build() {
    P.length = 0; US.length = 0;
    const phone = innerWidth < 640;
    const r = Math.random;
    const add = (lon, lat, us) => {
      const cl = Math.cos(lat * D2R);
      P.push({
        px: cl * Math.cos(lon * D2R), py: Math.sin(lat * D2R), pz: cl * Math.sin(lon * D2R),
        us, coarse: false, lod: 0, mx: 0, my: 0,     // lod 1: the half the lite level leaves out
        bucket: 0, size: 1, alpha: 0.3,
        a1: r() * Math.PI * 2, a2: r() * Math.PI * 2,
        f1: 0.22 + r() * 0.35, f2: 0.16 + r() * 0.3,
        amp: 1, tw: r() * Math.PI * 2,
        ig: Infinity,                                  // white-wave ignition time
        ox: 0, oy: 0, vx: 0, vy: 0,                    // pointer push: displacement and its velocity, px
        x: -1e4, y: -1e4
      });
    };
    // world: every dot on desktop, every other on phones. US: every 2nd / every 4th.
    // Every other dot is marked lod 1: the lite level (see the governor) leaves those out.
    const w = GEO.world, wStride = phone ? 4 : 2;
    for (let i = 0, n = 0; i < w.length; i += wStride, n++) { add(w[i] / 10, w[i + 1] / 10, false); P[P.length - 1].lod = n & 1; }
    const u = GEO.us, uStride = phone ? 8 : 4;
    for (let i = 0; i < u.length; i += uStride) { US.push(P.length); add(u[i] / 100, u[i + 1] / 100, true); }
    // On the globe the US shows only every COARSE-th of its dots, matching the
    // world grid's density; the rest arrive with the zoom. Those coarse dots always stay.
    const COARSE = Math.max(1, Math.round(GEO.ws * GEO.ws / (GEO.uss * GEO.uss * (uStride / 2))));
    for (let k = 0; k < US.length; k++) { const p = P[US[k]]; p.coarse = k % COARSE === 0; p.lod = p.coarse ? 0 : k & 1; }

    // Project everything with the landed camera once, frame the US, and lay it on the sheet.
    const c0 = Math.cos(US_LON * D2R), s0 = Math.sin(US_LON * D2R);
    const cL = Math.cos(US_LAT * D2R), sL = Math.sin(US_LAT * D2R);
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    const land = P.map(p => {
      const x = p.pz * c0 - p.px * s0, t = p.px * c0 + p.pz * s0;
      return [x, cL * p.py - sL * t];
    });
    for (const i of US) {
      const [x, y] = land[i];
      if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y;
    }
    kplane = 960 / (x1 - x0); bx0 = x0; by1 = y1;
    DATA.w = 960; DATA.h = (y1 - y0) * kplane;
    UC[0] = (x0 + x1) / 2; UC[1] = (y0 + y1) / 2;
    for (let i = 0; i < P.length; i++) {
      P[i].mx = (land[i][0] - bx0) * kplane;
      P[i].my = (by1 - land[i][1]) * kplane;
    }
    // colour and depth, as a flat map would get them
    let cx = 0, cy = 0;
    for (const i of US) { cx += P[i].mx; cy += P[i].my; }
    cx /= US.length; cy /= US.length;
    for (const p of P) {
      const ang = Math.atan2(-(p.my - cy), -(p.mx - cx));
      const a01 = ((ang / (Math.PI * 2)) % 1 + 1) % 1;
      const hue = hueAt(a01) + (noise2(p.mx, p.my) - 0.5) * 30 + (r() * 2 - 1) * 5;
      const z = r();                                   // depth: 0 far/dim, 1 near/bright
      p.bucket = bucketFor(hue);
      p.size = (0.6 + Math.pow(r(), 3.2) * 2.2) * (0.5 + z * 0.8);
      p.alpha = 0.14 + z * 0.5;
      p.amp = (1.0 + r() * 2.0) * (0.5 + z);
    }
    // the web: ~1 in 3 US dots linked to its nearest neighbor on the sheet.
    // Drawn faint blue always; segments light up white when both ends are flashing.
    LINKS.length = 0;
    for (let a = 0; a < US.length; a += 3) {
      const i = US[a];
      let best = -1, bd = 17 * 17;
      for (let b = Math.max(0, a - 300); b < Math.min(US.length, a + 300); b++) {
        const j = US[b];
        if (j === i) continue;
        const dx = P[i].mx - P[j].mx, dy = P[i].my - P[j].my, d = dx * dx + dy * dy;
        if (d < bd) { bd = d; best = j; }
      }
      if (best >= 0) LINKS.push([i, best]);
    }
    // walk graph: every US dot's 3 nearest neighbors within 18 sheet units,
    // found with a spatial hash (index order is not spatial, so no windows here)
    const CS = 18, HASH = new Map();
    const key = (gx, gy) => gx * 4096 + gy;
    for (const i of US) {
      const k = key((P[i].mx / CS) | 0, (P[i].my / CS) | 0);
      let b = HASH.get(k); if (!b) { b = []; HASH.set(k, b); }
      b.push(i);
    }
    ADJ.length = 0;
    for (let i = 0; i < P.length; i++) ADJ.push([]);
    for (const i of US) {
      const gx = (P[i].mx / CS) | 0, gy = (P[i].my / CS) | 0;
      const cand = [];
      for (let ax = -1; ax <= 1; ax++) for (let ay = -1; ay <= 1; ay++) {
        const b = HASH.get(key(gx + ax, gy + ay));
        if (b) for (const j of b) {
          if (j === i) continue;
          const dx = P[i].mx - P[j].mx, dy = P[i].my - P[j].my, d = dx * dx + dy * dy;
          if (d < CS * CS) cand.push([d, j]);
        }
      }
      cand.sort((a, b) => a[0] - b[0]);
      ADJ[i] = cand.slice(0, 3).map(c => c[1]);
    }
  }

  // ---- localized white pulls ---------------------------------------------------
  // While the country is formed, county-sized pockets flash white: a random spot
  // ignites and blooms outward over a small radius, every point inside flashes,
  // then cools back to blue. Several pockets stagger across the map at once.
  let nextPulse = 0;
  const FLASH = 1.5, F_IN = 0.18;                    // node flash lifetime / attack
  const STEP = 0.055;                                // seconds per hop along a string
  const STRINGS = [];                                // active strings: {seq:[idx], t0}
  function flashAt(p, t) {
    const g = t - p.ig;
    if (g <= 0 || g >= FLASH) return 0;
    return g < F_IN ? g / F_IN : 1 - (g - F_IN) / (FLASH - F_IN);
  }
  // A "string" is a random walk along the web: white crawls node-to-node,
  // lighting each node and the edge behind it, then fades like a cooling wire.
  function walk(start, maxLen, visited) {
    const seq = [start];
    visited.add(start);
    let cur = start;
    while (seq.length < maxLen) {
      const nbrs = ADJ[cur].filter(j => !visited.has(j) && P[j].lod <= quality);
      if (!nbrs.length) break;
      cur = nbrs[(Math.random() * nbrs.length) | 0];
      visited.add(cur);
      seq.push(cur);
    }
    return seq;
  }
  function spawnString(t) {
    const start = US[(Math.random() * US.length) | 0];
    const visited = new Set();
    const main = walk(start, 30 + (Math.random() * 20 | 0), visited);
    if (main.length < 6) return;                     // isolated node; skip
    const t0 = t + 0.05;
    const strings = [{ seq: main, t0 }];
    // one branch off the middle of the main string
    const bi = (main.length * (0.3 + Math.random() * 0.4)) | 0;
    const branch = walk(main[bi], 10 + (Math.random() * 10 | 0), visited);
    if (branch.length > 4) strings.push({ seq: branch, t0: t0 + bi * STEP });
    for (const s of strings) {
      for (let k = 0; k < s.seq.length; k++) {
        const p = P[s.seq[k]];
        const busy = t - p.ig > 0 && t - p.ig < FLASH;
        if (!busy) p.ig = s.t0 + k * STEP;
      }
      STRINGS.push(s);
    }
  }

  const PUSH_R = 0.12, PUSH_F = 3200, PUSH_V = 9;
  const SPRING_K = 90, SPRING_C = 11;
  const mouse = { on: false, x: -1e4, y: -1e4, vx: 0, vy: 0, t: 0 };
  const drag = { on: false, pointerId: null, x: 0, y: 0, t: 0, velocity: [0, 0, 0] };
  let exploring = false, holdUntil = 0, pullback = null, resetting = null;
  let interactionUntil = 0;
  let orientation = fromCamera(-58 + SPIN * 6, GLOBE_LAT);
  const ROT = new Float64Array(9);
  const clampV = v => Math.max(-3000, Math.min(3000, v));

  function pointerPosition(e) {
    const rect = canvas.getBoundingClientRect();
    return [(e.clientX - rect.left) * W / rect.width, (e.clientY - rect.top) * H / rect.height];
  }
  function stopMomentum() {
    drag.velocity.fill(0);
  }
  function setExploring(value) {
    exploring = value;
    hero.dataset.exploring = String(value);
    interactionUntil = performance.now() + 10000;
    stopMomentum(); resetting = null;
    sceneTime = 0;
    holdUntil = performance.now() + 1400;
    if (value) {
      orientation = [...CAM.q];
      pullback = reduced || CAM.z === 0 ? null : { z: CAM.z, start: performance.now(), duration: 650 };
    }
    redraw();
  }
  function resetOrientation() {
    if (!exploring) setExploring(true);
    stopMomentum();
    const target = fromCamera(-58, GLOBE_LAT);
    if (reduced || still) { orientation = target; redraw(); }
    else resetting = { from: [...orientation], to: target, start: performance.now() };
  }
  function onDown(e) {
    if (e.button !== 0 || drag.on || (!exploring && CAM.z > 0.15)) return;
    const [x, y] = pointerPosition(e);
    if (!exploring) setExploring(true);
    orientation = [...CAM.q];
    sceneTime = 0; zoomFrom = null;
    if (!pullback && CAM.z > 0) pullback = { z: CAM.z, start: performance.now(), duration: 350 };
    drag.on = true; drag.pointerId = e.pointerId; drag.x = x; drag.y = y; drag.t = e.timeStamp;
    stopMomentum(); resetting = null;
    interactionUntil = performance.now() + 10000;
    holdUntil = performance.now() + 6000;
    try { canvas.setPointerCapture(e.pointerId); } catch {}
    e.preventDefault();
  }
  function onMove(e) {
    if (e.pointerType === 'touch' && !exploring) return;
    if (drag.on && e.pointerId !== drag.pointerId) return;
    interactionUntil = performance.now() + 10000;
    const [x, y] = pointerPosition(e), now = e.timeStamp;
    if (mouse.on) {
      const dt = Math.max(0.008, (now - mouse.t) / 1000);
      mouse.vx = clampV((x - mouse.x) / dt); mouse.vy = clampV((y - mouse.y) / dt);
    }
    mouse.x = x; mouse.y = y; mouse.t = now; mouse.on = true;
    if (!drag.on) return;
    const centerX = W / 2 - CAM.cx * CAM.R, centerY = H / 2 + CAM.cy * CAM.R;
    const delta = dragRotation(drag.x - centerX, drag.y - centerY, x - centerX, y - centerY, CAM.R);
    orientation = multiply(delta, orientation);
    const length = Math.hypot(delta[0], delta[1], delta[2]);
    if (length > 1e-6) {
      const dt = Math.max(0.004, (now - drag.t) / 1000);
      const speed = 2 * Math.atan2(length, delta[3]) / dt;
      const weight = 0.6;
      for (let i = 0; i < 3; i++) drag.velocity[i] += (delta[i] / length * speed - drag.velocity[i]) * weight;
      drag.t = now;
    }
    drag.x = x; drag.y = y;
    holdUntil = performance.now() + 6000;
    redraw();
  }
  function onUp(e) {
    if (e.pointerId !== drag.pointerId) return;
    if (e.type !== 'pointerup' || e.timeStamp - drag.t > 100) stopMomentum();
    drag.on = false; drag.pointerId = null;
    interactionUntil = performance.now() + 10000;
    mouse.vx = mouse.vy = 0;
    holdUntil = performance.now() + 6000;
    try { canvas.releasePointerCapture(e.pointerId); } catch {}
    redraw();
  }
  function onLeave() { mouse.on = false; mouse.vx = mouse.vy = 0; }
  function attachPointer(el) {
    el.addEventListener('pointerdown', onDown);
    el.addEventListener('pointermove', onMove);
    el.addEventListener('pointerup', onUp);
    el.addEventListener('pointercancel', onUp);
    el.addEventListener('lostpointercapture', onUp);
    el.addEventListener('pointerleave', onLeave);
    el.addEventListener('keydown', e => {
      if (e.key === 'Escape') { setExploring(false); return; }
      if (e.key === 'Home') { e.preventDefault(); resetOrientation(); return; }
      if (!['ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown', 'q', 'e'].includes(e.key)) return;
      e.preventDefault();
      if (!exploring) setExploring(true);
      interactionUntil = performance.now() + 10000;
      resetting = null; stopMomentum();
      const angle = 0.12;
      const delta = e.key === 'ArrowLeft' ? axisAngle(0, 1, 0, -angle)
        : e.key === 'ArrowRight' ? axisAngle(0, 1, 0, angle)
        : e.key === 'ArrowUp' ? axisAngle(1, 0, 0, -angle)
        : e.key === 'ArrowDown' ? axisAngle(1, 0, 0, angle)
        : axisAngle(0, 0, 1, e.key === 'q' ? angle : -angle);
      orientation = multiply(delta, orientation);
      redraw();
    });
  }
  function spinStep(dt, ms) {
    if (resetting) {
      const amount = Math.min(1, (ms - resetting.start) / 650);
      orientation = slerp(resetting.from, resetting.to, easeInOut(amount));
      if (amount === 1) resetting = null;
      return;
    }
    if (drag.on || CAM.z > 0.15 || pullback || reduced || still) return;
    const speed = Math.hypot(...drag.velocity);
    if (speed > 0.008) {
      const decay = Math.exp(-dt * 1.8);
      orientation = multiply(axisAngle(...drag.velocity, speed * (1 - decay) / 1.8), orientation);
      for (let i = 0; i < 3; i++) drag.velocity[i] *= decay;
    } else if (!exploring && ms >= holdUntil) {
      orientation = multiply(orientation, axisAngle(0, 1, 0, SPIN * D2R * dt));
    }
  }

  function layout() {
    dpr = Math.min(devicePixelRatio || 1, gl ? 2 : 1.5, quality < 2 ? 1 : 2);   // Retina on WebGL at full; the 2D path is capped; lite and still draw 1:1
    BW = hero.clientWidth; BH = hero.clientHeight;
    W = Math.round(BW * (1 + 2 * PAD_X)); H = Math.round(BH * (1 + 2 * PAD_Y));
    canvas.width = Math.round(W * dpr); canvas.height = Math.round(H * dpr);
    canvas.style.width = W + 'px'; canvas.style.height = H + 'px';
    canvas.style.left = -Math.round(BW * PAD_X) + 'px'; canvas.style.top = -Math.round(BH * PAD_Y) + 'px';
    if (gl) gl.viewport(0, 0, canvas.width, canvas.height); else ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    scale = Math.min(BW * 0.94 / DATA.w, BH * 0.92 / DATA.h);
    R_LAND = kplane * scale;                           // landed: the US fills the box
    R_GLOBE = BH * 0.46;                               // on the globe: the sphere fits the box
  }

  const T_GLOBE = 6, T_ZOOM = 4.2, T_HOLD = 9, T_BACK = 4.2;
  const T_LOOP = T_GLOBE + T_ZOOM + T_HOLD + T_BACK;
  const easeInOut = u => u < 0.5 ? 2 * u * u : 1 - (1 - u) * (1 - u) * 2;
  const clamp01 = u => Math.max(0, Math.min(1, u));
  const smooth = (a, b, u) => { u = clamp01((u - a) / (b - a)); return u * u * (3 - 2 * u); };
  const LAND_Q = fromCamera(US_LON, US_LAT);
  const CAM = { q: [...orientation], R: 1, cx: 0, cy: 0, z: 0 };
  let sceneTime = 0, zoomFrom = null;
  function camera(ms) {
    let u = sceneTime % T_LOOP, z;
    if (pullback) {
      const amount = Math.min(1, (ms - pullback.start) / pullback.duration);
      z = pullback.z * (1 - easeInOut(amount));
      CAM.q = orientation;
      if (amount === 1) pullback = null;
    } else if (exploring || u < T_GLOBE) {
      z = 0; CAM.q = orientation; zoomFrom = null;
    } else if ((u -= T_GLOBE) < T_ZOOM) {
      z = easeInOut(u / T_ZOOM);
      if (!zoomFrom) zoomFrom = [...orientation];
      CAM.q = slerp(zoomFrom, LAND_Q, z);
    } else if ((u -= T_ZOOM) < T_HOLD) {
      z = 1; CAM.q = LAND_Q;
    } else {
      z = 1 - easeInOut((u - T_HOLD) / T_BACK);
      CAM.q = slerp(LAND_Q, orientation, 1 - z);
    }
    CAM.z = z;
    CAM.R = Math.exp(Math.log(R_GLOBE) + (Math.log(R_LAND) - Math.log(R_GLOBE)) * z);
    CAM.cx = UC[0] * z; CAM.cy = UC[1] * z;
  }
  function landed() { CAM.z = 1; CAM.q = LAND_Q; CAM.R = R_LAND; CAM.cx = UC[0]; CAM.cy = UC[1]; }

  // ---- the governor ----------------------------------------------------------
  // The machine sets the pace. Once the loop has warmed up, the gap between
  // frames is sampled; when the typical gap runs long, so the whole page would
  // stutter, the hero steps down a level and stays there:
  //   2 full   every dot, Retina
  //   1 lite   every other dot, no Retina
  //   0 still  the loop stops; one frame of the globe holds, and dragging or keys redraw it
  // A machine far over the budget goes straight to still. The level is written
  // on the box as data-quality. The loop also rests while the field is off screen.
  let quality = 2, still = false, visible = true, queued = false, lostAt = 0;
  const SLOW_MS = 40;                                  // a typical gap over this (under 25 fps) is a step down
  const SAMPLES = new Float32Array(16);
  let sampled = 0, settleAt = performance.now() + 1200;
  function setQuality(q) {
    quality = q;
    hero.dataset.quality = ['still', 'lite', 'full'][q];
    sampled = 0; settleAt = performance.now() + 1000;
    if (q === 0) {                                     // hold the globe, not whatever the tour was doing
      still = true; exploring = false; hero.dataset.exploring = 'false';
      pullback = null; resetting = null; zoomFrom = null; sceneTime = 0; stopMomentum();
    }
    if (q < 2) layout();
  }
  function govern(ms, gap) {
    if (quality === 0 || ms < settleAt) return;
    SAMPLES[sampled++] = gap;
    if (sampled < SAMPLES.length) return;
    const median = Array.from(SAMPLES).sort((a, b) => a - b)[SAMPLES.length >> 1];
    if (median > SLOW_MS) setQuality(median > SLOW_MS * 2.5 ? 0 : quality - 1);
    else sampled = 0;
  }
  function schedule() {
    if (queued || reduced || still || !visible) return;
    queued = true;
    requestAnimationFrame(ms => { queued = false; frame(ms); schedule(); });
  }
  function redraw() { if (reduced || still) frame(performance.now()); }   // one frame, when nothing loops

  // ---- render ----------------------------------------------------------------
  // frame() moves the camera, projects every dot and writes what the drawing
  // needs into DYN (x, y, size, alpha, flash per dot: five floats each); then
  // drawGL() or draw2D() paints that.
  let DYN = new Float32Array(0);             // sized once build() has run
  let lastMs = 0, cursor = '';
  function frame(ms) {
    const dt = lastMs ? Math.min(0.05, (ms - lastMs) / 1000) : 1 / 60;
    if (lastMs && !reduced && !still) govern(ms, ms - lastMs);
    lastMs = ms;
    const t = ms / 1000;
    if (!reduced && !still && exploring && !drag.on && ms >= interactionUntil) setExploring(false);
    if (reduced && !exploring) landed();
    else {
      spinStep(dt, ms);
      if (!exploring && !drag.on && ms >= holdUntil && !pullback && !still) sceneTime += dt;
      camera(ms);
    }
    const { R, cx, cy, z } = CAM;
    matrix(CAM.q, ROT);
    const X0 = W / 2 - cx * R, Y0 = H / 2 + cy * R;    // screen = X0 + x*R, Y0 - y*R

    // the hand: grab while the globe is up, nothing once landed
    const cur = drag.on ? 'grabbing' : exploring || z <= 0.15 ? 'grab' : '';
    if (cur !== cursor) { cursor = cur; canvas.style.cursor = cur; }

    const detail = smooth(0.2, 0.8, z);                // the fine US dots arrive with the zoom
    const dim = 1 - smooth(0.5, 0.95, z);              // the rest of the world fades out as the camera lands
    const dotMul = 0.82 + 0.18 * z;                    // dots grow with the camera
    const wob = 0.35 + 0.65 * z;                       // drift: calm on the globe
    const formAmount = reduced ? 1 : smooth(0.85, 1, z);

    // spawn white strings while the country is formed
    if (!reduced && z > 0.97 && t >= nextPulse && STRINGS.length < 8) {
      spawnString(t);
      nextPulse = t + 0.9 + Math.random() * 0.8;
    }
    if (z < 0.95) STRINGS.length = 0;                  // the pull-back: no filaments while the map comes apart
    // retire strings whose last node has fully cooled
    for (let k = STRINGS.length - 1; k >= 0; k--) {
      const s = STRINGS[k];
      if (t > s.t0 + s.seq.length * STEP + FLASH) STRINGS.splice(k, 1);
    }

    // the pointer's push: only while it is over the field; its speed goes stale fast
    const push = !reduced && mouse.on && !drag.on;
    if (push && ms - mouse.t > 60) mouse.vx = mouse.vy = 0;
    const PR = Math.max(40, BW * PUSH_R), PR2 = PR * PR;
    const EDGE_Y = Math.max(EDGE, BH * PAD_Y);             // above and below the box, dots fade over the whole overflow
    const mx = mouse.x, my = mouse.y, mvx = mouse.vx * PUSH_V, mvy = mouse.vy * PUSH_V;

    for (let i = 0, o = 0; i < P.length; i++, o += 5) {
      const p = P[i];
      const x = ROT[0] * p.pz + ROT[1] * p.py + ROT[2] * p.px;
      const y = ROT[3] * p.pz + ROT[4] * p.py + ROT[5] * p.px;
      const zc = ROT[6] * p.pz + ROT[7] * p.py + ROT[8] * p.px;
      let a = 0;
      if (zc > 0.02 && p.lod <= quality) {             // the near side only; lite leaves half the dots out
        a = p.alpha * (0.3 + 0.7 * zc) * (1 + 0.85 * (1 - z));   // limb shading; brighter on the globe
        a *= p.us ? (p.coarse ? 1 : detail) : dim;
      }
      if (a < 0.01) { p.x = -1e4; DYN[o] = -1e4; DYN[o + 1] = -1e4; DYN[o + 3] = 0; DYN[o + 4] = 0; continue; }
      const fx = reduced ? 0 : Math.sin(t * p.f1 + p.a1) * p.amp * wob;
      const fy = reduced ? 0 : Math.cos(t * p.f2 + p.a2) * p.amp * wob;
      let sx = X0 + x * R + fx, sy = Y0 - y * R + fy;
      // the push, then the spring back
      let ox = p.ox, oy = p.oy, vx = p.vx, vy = p.vy;
      if (push) {
        const ddx = sx - mx, ddy = sy - my, d2 = ddx * ddx + ddy * ddy;
        if (d2 < PR2) {
          const d = Math.sqrt(d2) + 1e-3, f = 1 - d / PR, g = f * f * dt;
          vx += (ddx / d) * PUSH_F * g + mvx * g;
          vy += (ddy / d) * PUSH_F * g + mvy * g;
        }
      }
      if (ox !== 0 || oy !== 0 || vx !== 0 || vy !== 0) {
        vx += (-SPRING_K * ox - SPRING_C * vx) * dt;
        vy += (-SPRING_K * oy - SPRING_C * vy) * dt;
        ox += vx * dt; oy += vy * dt;
        if (ox * ox + oy * oy < 0.01 && vx * vx + vy * vy < 1) ox = oy = vx = vy = 0;   // settled
        p.ox = ox; p.oy = oy; p.vx = vx; p.vy = vy;
        sx += ox; sy += oy;
      }
      p.x = sx; p.y = sy;
      DYN[o] = sx; DYN[o + 1] = sy;
      if (sx < -16 || sx > W + 16 || sy < -16 || sy > H + 16) { DYN[o + 3] = 0; DYN[o + 4] = 0; continue; }
      const ef = Math.min(sx / EDGE, (W - sx) / EDGE, sy / EDGE_Y, (H - sy) / EDGE_Y);   // soft edges: nothing is cut off hard
      const edge = ef >= 1 ? 1 : ef <= 0 ? 0 : ef * ef;
      const tw = reduced ? 1 : 0.78 + 0.22 * Math.sin(t * 1.25 + p.tw);
      DYN[o + 2] = p.size * 3.2 * dotMul;
      DYN[o + 3] = a * tw * edge;
      const gm = flashAt(p, t);                        // white overlay on a flashing node
      DYN[o + 4] = gm > 0 ? Math.min(1, gm * (0.35 + p.alpha * 0.8)) * edge : 0;
    }

    if (gl && !G && lostAt && ms - lostAt > 2000) useCanvas2D();   // a context lost for good: carry on in 2D
    if (gl) drawGL(z, X0, Y0, R, formAmount, t); else draw2D(z, X0, Y0, R, formAmount, t);
  }

  // the sphere's body fades away as it outgrows the box, instead of being clipped
  function discFade(R) { const k = (R_GLOBE * 1.3 - R) / (R_GLOBE * 0.3); return k < 0 ? 0 : k > 1 ? 1 : k; }

  const globeGrid = [];
  function spherePoint(lon, lat) {
    const c = Math.cos(lat * D2R);
    return [c * Math.sin(lon * D2R), Math.sin(lat * D2R), c * Math.cos(lon * D2R)];
  }
  for (let latitude = -60; latitude <= 60; latitude += 30) {
    for (let longitude = -180; longitude < 180; longitude += 4) {
      globeGrid.push(...spherePoint(longitude, latitude), ...spherePoint(longitude + 4, latitude));
    }
  }
  for (let longitude = -180; longitude < 180; longitude += 30) {
    for (let latitude = -88; latitude < 88; latitude += 4) {
      globeGrid.push(...spherePoint(longitude, latitude), ...spherePoint(longitude, latitude + 4));
    }
  }
  function drawGlobeGrid(z, X0, Y0, R) {
    const alpha = (1 - z) * discFade(R) * 0.13;
    if (alpha < 0.001) return;
    if (gl) lineBegin(0.65);
    else { ctx.beginPath(); ctx.lineWidth = 0.65; ctx.strokeStyle = 'rgba(100,160,240,' + alpha + ')'; }
    for (let i = 0; i < globeGrid.length; i += 6) {
      const ax = globeGrid[i], ay = globeGrid[i + 1], az = globeGrid[i + 2];
      const bx = globeGrid[i + 3], by = globeGrid[i + 4], bz = globeGrid[i + 5];
      if (ROT[6] * ax + ROT[7] * ay + ROT[8] * az < 0.035 || ROT[6] * bx + ROT[7] * by + ROT[8] * bz < 0.035) continue;
      const x1 = X0 + (ROT[0] * ax + ROT[1] * ay + ROT[2] * az) * R;
      const y1 = Y0 - (ROT[3] * ax + ROT[4] * ay + ROT[5] * az) * R;
      const x2 = X0 + (ROT[0] * bx + ROT[1] * by + ROT[2] * bz) * R;
      const y2 = Y0 - (ROT[3] * bx + ROT[4] * by + ROT[5] * bz) * R;
      if (gl) lineAdd(x1, y1, x2, y2);
      else { ctx.moveTo(x1, y1); ctx.lineTo(x2, y2); }
    }
    if (gl) lineFlush(0.39, 0.63, 0.94, alpha);
    else ctx.stroke();
  }

  // the 2D-canvas fallback: the same frame, one sprite at a time
  function draw2D(z, X0, Y0, R, formAmount, t) {
    ctx.globalCompositeOperation = 'source-over';
    ctx.globalAlpha = 1;
    ctx.clearRect(0, 0, W, H);
    // the sphere's body: a faint disc and rim so the globe reads against the dark
    if (z < 0.999) {
      const g = ctx.createRadialGradient(X0, Y0, R * 0.25, X0, Y0, R);
      g.addColorStop(0,   'rgba(30,65,130,0.42)');
      g.addColorStop(0.8, 'rgba(18,42,88,0.28)');
      g.addColorStop(1,   'rgba(10,16,40,0)');
      ctx.globalAlpha = (1 - z) * discFade(R);
      ctx.fillStyle = g;
      ctx.beginPath(); ctx.arc(X0, Y0, R, 0, Math.PI * 2); ctx.fill();
      ctx.lineWidth = 1;
      ctx.strokeStyle = 'rgba(120,180,255,0.45)';
      ctx.stroke();
    }
    ctx.globalAlpha = 1;
    drawGlobeGrid(z, X0, Y0, R);
    ctx.globalCompositeOperation = 'lighter';          // additive: overlaps bloom
    for (let i = 0, o = 0; i < P.length; i++, o += 5) {
      const a = DYN[o + 3];
      if (a <= 0) continue;
      const x = DYN[o], y = DYN[o + 1], s = DYN[o + 2];
      ctx.globalAlpha = a;
      ctx.drawImage(SPRITES[P[i].bucket], x - s / 2, y - s / 2, s, s);
      const f = DYN[o + 4];
      if (f > 0) {
        ctx.globalAlpha = f;
        const gs = s * 1.1;
        ctx.drawImage(WHITE, x - gs / 2, y - gs / 2, gs, gs);
      }
    }
    ctx.globalAlpha = 1;
    // the blue web, ONE batched path; only once the US has formed
    if (formAmount > 0) {
      ctx.lineWidth = 0.5;
      ctx.strokeStyle = 'rgba(105,145,255,' + 0.03 * formAmount + ')';
      ctx.beginPath();
      for (const [i, j] of LINKS) {
        if (P[i].x === -1e4 || P[j].x === -1e4) continue;
        ctx.moveTo(P[i].x, P[i].y);
        ctx.lineTo(P[j].x, P[j].y);
      }
      ctx.stroke();
    }
    // white strings: each walk's consecutive edges where both ends still glow
    if (!reduced && STRINGS.length) {
      ctx.lineWidth = 0.9;
      ctx.strokeStyle = 'rgba(255,255,255,0.5)';
      ctx.beginPath();
      for (const s of STRINGS) {
        for (let k = 1; k < s.seq.length; k++) {
          const A = P[s.seq[k - 1]], B = P[s.seq[k]];
          if (A.x === -1e4 || B.x === -1e4) continue;
          if (flashAt(A, t) > 0.08 && flashAt(B, t) > 0.08) {
            ctx.moveTo(A.x, A.y);
            ctx.lineTo(B.x, B.y);
          }
        }
      }
      ctx.stroke();
    }
  }

  // ---- WebGL -----------------------------------------------------------------
  // Three small programs: the globe's disc, the dots (point sprites whose glow
  // is computed per pixel, so no textures), and lines (each segment a thin quad
  // with a feathered edge). Positions are css px; the vertex shaders map them.
  let G = null;                              // programs, buffers and uniform locations
  const VS_DOT = `
  attribute vec2 aPos; attribute float aSize; attribute float aAlpha; attribute float aFlash; attribute vec3 aCol;
  uniform vec2 uRes; uniform float uDpr;
  varying vec3 vCol; varying float vA; varying float vF;
  void main() {
    vec2 c = aPos / uRes * 2.0 - 1.0;
    gl_Position = vec4(c.x, -c.y, 0.0, 1.0);
    float ps = aSize * 1.1 * uDpr;                 // the flare sits 10% outside the dot
    gl_PointSize = max(ps, 1.5);
    float k = min(1.0, ps / 1.5);                  // sub-pixel dots fade instead of popping
    vCol = aCol; vA = aAlpha * k * k; vF = aFlash * k * k;
  }`;
  const FS_DOT = `
  precision mediump float;
  varying vec3 vCol; varying float vA; varying float vF;
  void main() {
    float d = length(gl_PointCoord - 0.5) * 2.0;   // 0 at the centre, 1 at the sprite's rim
    float e = d * 1.1;                             // in units of the dot's own radius
    vec3 rgb; float a;                             // the glow: white core -> colour -> clear
    if (e < 0.18)     { float u = e / 0.18;          rgb = mix(vec3(1.0), vCol, u); a = mix(0.9, 0.85, u); }
    else if (e < 0.5) { float u = (e - 0.18) / 0.32; rgb = vCol; a = mix(0.85, 0.1, u); }
    else              { float u = min(1.0, (e - 0.5) / 0.5); rgb = vCol; a = mix(0.1, 0.0, u); }
    float dotA = a * vA, flareA = 0.0;
    if (vF > 0.0) {                                // the white flare on a flashing node
      float w;
      if (d < 0.2)       w = mix(0.95, 0.9, d / 0.2);
      else if (d < 0.55) w = mix(0.9, 0.25, (d - 0.2) / 0.35);
      else               w = mix(0.25, 0.0, min(1.0, (d - 0.55) / 0.45));
      flareA = w * vF;
    }
    // premultiplied: colour and coverage both add onto the transparent canvas
    gl_FragColor = vec4(rgb * dotA + vec3(flareA), min(1.0, dotA + flareA));
  }`;
  const VS_LINE = `
  attribute vec2 aPos; attribute float aEdge;
  uniform vec2 uRes;
  varying float vE;
  void main() { vec2 c = aPos / uRes * 2.0 - 1.0; gl_Position = vec4(c.x, -c.y, 0.0, 1.0); vE = aEdge; }`;
  const FS_LINE = `
  precision mediump float;
  uniform vec4 uCol; uniform float uFeather;
  varying float vE;
  void main() {
    float a = uCol.a * (1.0 - smoothstep(uFeather, 1.0, abs(vE)));   // soft edge, one device px
    gl_FragColor = vec4(uCol.rgb * a, a);
  }`;
  // The sphere's body is shaded on a quad just around it, not the whole canvas,
  // and each pixel's place arrives in sphere radii from the vertex stage: small
  // numbers, so medium precision does where a GPU has no high precision.
  const VS_DISC = `
  attribute vec2 aPos;
  uniform vec2 uRes; uniform vec2 uC; uniform float uR;
  varying vec2 vV;
  void main() {
    vec2 c = aPos / uRes * 2.0 - 1.0;
    gl_Position = vec4(c.x, -c.y, 0.0, 1.0);
    vV = (aPos - uC) / uR;                         // this corner, in sphere radii, y down
  }`;
  const FS_DISC = `
  #ifdef GL_FRAGMENT_PRECISION_HIGH
  precision highp float;
  #else
  precision mediump float;
  #endif
  uniform float uR; uniform float uA;
  varying vec2 vV;
  void main() {
    vec2 v = vV;
    float r = length(v);
    float front = sqrt(max(0.0, 1.0 - r * r));
    vec3 normal = vec3(v.x, -v.y, front);
    float light = max(0.0, dot(normal, normalize(vec3(-0.55, 0.65, 0.8))));
    float inside = 1.0 - smoothstep(0.995, 1.005, r);
    vec3 ocean = mix(vec3(0.008, 0.015, 0.035), vec3(0.035, 0.09, 0.19), light);
    float body = (0.48 + light * 0.18) * inside;
    float atmosphere = exp(-abs(r - 1.0) * 46.0) * (0.12 + 0.20 * light);
    float rim = (1.0 - smoothstep(0.35, 1.2, abs(r - 1.0) * uR)) * (0.22 + 0.32 * light);
    float halo = exp(-pow((r - 1.015) / 0.065, 2.0)) * smoothstep(0.98, 1.01, r) * 0.06;
    vec3 col = ocean * body + vec3(0.22, 0.55, 1.0) * (atmosphere + halo) + vec3(0.55, 0.78, 1.0) * rim;
    float alpha = min(1.0, body + atmosphere + rim + halo);
    gl_FragColor = vec4(col * uA, alpha * uA);
  }`;
  function shader(type, src) {
    const s = gl.createShader(type);
    gl.shaderSource(s, src); gl.compileShader(s);
    if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) throw new Error(gl.getShaderInfoLog(s));
    return s;
  }
  function program(vs, fs) {
    const p = gl.createProgram();
    gl.attachShader(p, shader(gl.VERTEX_SHADER, vs));
    gl.attachShader(p, shader(gl.FRAGMENT_SHADER, fs));
    gl.linkProgram(p);
    if (!gl.getProgramParameter(p, gl.LINK_STATUS)) throw new Error(gl.getProgramInfoLog(p));
    return p;
  }
  function initGL() {
    gl.clearColor(0, 0, 0, 0);                           // clear to transparent
    gl.disable(gl.DEPTH_TEST); gl.enable(gl.BLEND);
    const dot = program(VS_DOT, FS_DOT), line = program(VS_LINE, FS_LINE), disc = program(VS_DISC, FS_DISC);
    const u = (p, n) => gl.getUniformLocation(p, n), at = (p, n) => gl.getAttribLocation(p, n);
    G = {
      dot:  { p: dot, aPos: at(dot, 'aPos'), aSize: at(dot, 'aSize'), aAlpha: at(dot, 'aAlpha'),
              aFlash: at(dot, 'aFlash'), aCol: at(dot, 'aCol'), uRes: u(dot, 'uRes'), uDpr: u(dot, 'uDpr') },
      line: { p: line, aPos: at(line, 'aPos'), aEdge: at(line, 'aEdge'),
              uRes: u(line, 'uRes'), uCol: u(line, 'uCol'), uFeather: u(line, 'uFeather') },
      disc: { p: disc, aPos: at(disc, 'aPos'), uRes: u(disc, 'uRes'),
              uC: u(disc, 'uC'), uR: u(disc, 'uR'), uA: u(disc, 'uA') },
      bDyn: gl.createBuffer(), bCol: gl.createBuffer(), bLine: gl.createBuffer(), bDisc: gl.createBuffer()
    };
  }
  // what never changes: each dot's colour (the same 24 hues the sprites use)
  function uploadStatic() {
    const COL = new Float32Array(P.length * 3);
    for (let i = 0; i < P.length; i++) {
      const hue = BAND_LO + (P[i].bucket / (BUCKETS - 1)) * (BAND_HI - BAND_LO);
      const [r, g, b] = hslToRgb(hue, 0.85, 0.62);
      COL[i * 3] = r / 255; COL[i * 3 + 1] = g / 255; COL[i * 3 + 2] = b / 255;
    }
    gl.bindBuffer(gl.ARRAY_BUFFER, G.bCol);
    gl.bufferData(gl.ARRAY_BUFFER, COL, gl.STATIC_DRAW);
  }
  // lines: each segment becomes two triangles, hw wide, with an aEdge of -1..1
  // across the width so the fragment shader can feather the outer pixel
  const LQ = { arr: new Float32Array(0), n: 0, w: 0, hw: 0 };
  const QUAD = new Float32Array(12);                     // the sphere's quad, two triangles in css px
  function lineBegin(w) {
    LQ.n = 0; LQ.w = w;
    LQ.hw = (Math.max(w * dpr, 1) + 1) / 2 / dpr;        // half-width, css px, plus the feather
  }
  function lineAdd(ax, ay, bx, by) {
    const A = LQ.arr;
    let o = LQ.n * 18;
    if (o + 18 > A.length) return;
    const dx = bx - ax, dy = by - ay;
    const L = Math.sqrt(dx * dx + dy * dy) || 1;
    const nx = -dy / L * LQ.hw, ny = dx / L * LQ.hw;
    A[o++] = ax + nx; A[o++] = ay + ny; A[o++] = -1;
    A[o++] = ax - nx; A[o++] = ay - ny; A[o++] = 1;
    A[o++] = bx + nx; A[o++] = by + ny; A[o++] = -1;
    A[o++] = bx + nx; A[o++] = by + ny; A[o++] = -1;
    A[o++] = ax - nx; A[o++] = ay - ny; A[o++] = 1;
    A[o++] = bx - nx; A[o++] = by - ny; A[o++] = 1;
    LQ.n++;
  }
  function lineFlush(r, g, b, a) {
    if (!LQ.n) return;
    const l = G.line, wd = Math.max(LQ.w * dpr, 1), cov = Math.min(1, LQ.w * dpr);
    gl.useProgram(l.p);
    gl.uniform2f(l.uRes, W, H);
    gl.uniform4f(l.uCol, r, g, b, a * cov);              // thinner than a pixel: fainter instead
    gl.uniform1f(l.uFeather, wd / (wd + 1));
    gl.bindBuffer(gl.ARRAY_BUFFER, G.bLine);
    gl.bufferData(gl.ARRAY_BUFFER, LQ.arr.subarray(0, LQ.n * 18), gl.DYNAMIC_DRAW);
    gl.enableVertexAttribArray(l.aPos);  gl.vertexAttribPointer(l.aPos, 2, gl.FLOAT, false, 12, 0);
    gl.enableVertexAttribArray(l.aEdge); gl.vertexAttribPointer(l.aEdge, 1, gl.FLOAT, false, 12, 8);
    gl.drawArrays(gl.TRIANGLES, 0, LQ.n * 6);
    gl.disableVertexAttribArray(l.aPos); gl.disableVertexAttribArray(l.aEdge);
  }
  function drawGL(z, X0, Y0, R, formAmount, t) {
    if (!G) return;                                      // context lost; nothing to draw with
    gl.clear(gl.COLOR_BUFFER_BIT);
    // the sphere's body: a faint disc and rim so the globe reads against the dark,
    // shaded only on a quad around the sphere (its halo ends within 1.25 radii)
    const discA = (1 - z) * discFade(R);
    if (discA > 0.002) {
      const d = G.disc, e = R * 1.25;
      gl.useProgram(d.p);
      gl.blendFunc(gl.ONE, gl.ONE_MINUS_SRC_ALPHA);
      gl.uniform2f(d.uRes, W, H); gl.uniform2f(d.uC, X0, Y0); gl.uniform1f(d.uR, R); gl.uniform1f(d.uA, discA);
      QUAD.set([X0 - e, Y0 - e, X0 + e, Y0 - e, X0 - e, Y0 + e, X0 + e, Y0 - e, X0 + e, Y0 + e, X0 - e, Y0 + e]);
      gl.bindBuffer(gl.ARRAY_BUFFER, G.bDisc);
      gl.bufferData(gl.ARRAY_BUFFER, QUAD, gl.DYNAMIC_DRAW);
      gl.enableVertexAttribArray(d.aPos); gl.vertexAttribPointer(d.aPos, 2, gl.FLOAT, false, 0, 0);
      gl.drawArrays(gl.TRIANGLES, 0, 6);
      gl.disableVertexAttribArray(d.aPos);
    }
    gl.blendFunc(gl.ONE, gl.ONE);
    drawGlobeGrid(z, X0, Y0, R);
    // every dot, one call
    const q = G.dot;
    gl.useProgram(q.p);
    gl.uniform2f(q.uRes, W, H); gl.uniform1f(q.uDpr, dpr);
    gl.bindBuffer(gl.ARRAY_BUFFER, G.bDyn);
    gl.bufferData(gl.ARRAY_BUFFER, DYN, gl.DYNAMIC_DRAW);
    gl.enableVertexAttribArray(q.aPos);   gl.vertexAttribPointer(q.aPos,   2, gl.FLOAT, false, 20, 0);
    gl.enableVertexAttribArray(q.aSize);  gl.vertexAttribPointer(q.aSize,  1, gl.FLOAT, false, 20, 8);
    gl.enableVertexAttribArray(q.aAlpha); gl.vertexAttribPointer(q.aAlpha, 1, gl.FLOAT, false, 20, 12);
    gl.enableVertexAttribArray(q.aFlash); gl.vertexAttribPointer(q.aFlash, 1, gl.FLOAT, false, 20, 16);
    gl.bindBuffer(gl.ARRAY_BUFFER, G.bCol);
    gl.enableVertexAttribArray(q.aCol);   gl.vertexAttribPointer(q.aCol,   3, gl.FLOAT, false, 0, 0);
    gl.drawArrays(gl.POINTS, 0, P.length);
    for (const a of [q.aPos, q.aSize, q.aAlpha, q.aFlash, q.aCol]) gl.disableVertexAttribArray(a);
    // the blue web, only once the US has formed
    if (formAmount > 0) {
      lineBegin(0.5);
      for (const [i, j] of LINKS) {
        if (P[i].x === -1e4 || P[j].x === -1e4) continue;
        lineAdd(P[i].x, P[i].y, P[j].x, P[j].y);
      }
      lineFlush(105 / 255, 145 / 255, 1, 0.03 * formAmount);
    }
    // white strings: each walk's consecutive edges where both ends still glow
    if (!reduced && STRINGS.length) {
      lineBegin(0.9);
      for (const s of STRINGS) {
        for (let k = 1; k < s.seq.length; k++) {
          const A = P[s.seq[k - 1]], B = P[s.seq[k]];
          if (A.x === -1e4 || B.x === -1e4) continue;
          if (flashAt(A, t) > 0.08 && flashAt(B, t) > 0.08) lineAdd(A.x, A.y, B.x, B.y);
        }
      }
      lineFlush(1, 1, 1, 0.5);
    }
  }

  // ---- go --------------------------------------------------------------------
  makeSprites();
  makeWhite();
  build();
  DYN = new Float32Array(P.length * 5);
  LQ.arr = new Float32Array(Math.max(LINKS.length, 2048) * 18);
  // the 2D path: a fresh canvas (one that has had WebGL can't give a 2D context), same handlers
  function useCanvas2D() {
    gl = null; G = null; lostAt = 0;
    const fresh = canvas.cloneNode();
    canvas.replaceWith(fresh); canvas = fresh;
    ctx = canvas.getContext('2d');
    attachPointer(canvas);
    layout();
  }
  if (gl) {
    try { initGL(); uploadStatic(); }
    catch (err) { console.warn('Hero: WebGL unavailable, drawing in 2D.', err); gl = null; }   // a driver that can't take the shaders
  }
  if (gl) {
    canvas.addEventListener('webglcontextlost', e => { e.preventDefault(); G = null; lostAt = performance.now(); });
    canvas.addEventListener('webglcontextrestored', () => { initGL(); uploadStatic(); lostAt = 0; layout(); redraw(); });
    attachPointer(canvas);
    layout();
  } else useCanvas2D();
  addEventListener('resize', () => { layout(); redraw(); });
  if (typeof ResizeObserver !== 'undefined') {
    new ResizeObserver(() => { layout(); redraw(); }).observe(hero);
  }
  if (typeof IntersectionObserver !== 'undefined') {     // off screen, the loop rests and the page has the CPU
    new IntersectionObserver(entries => {
      visible = entries[entries.length - 1].isIntersecting;
      if (visible) { lastMs = 0; schedule(); }
    }).observe(hero);
  }
  hero.dataset.quality = 'full';
  if (reduced) frame(performance.now()); else schedule();
}

startHero().catch(error => {
  console.error('Hero unavailable:', error);
  // The decorative animation must never prevent reading the page or signing up.
  document.querySelector('.map').hidden = true;
});
